using System.Text;
using RobinEpple.Common.Html.Mdn;

Console.WriteLine("Starting MDN Fetch task...");

const string targetFolder = "/workspaces/common/src/Common.Html/MDN";
const string targetNamespace = "RobinEpple.Common.Html.Components";
var excludeAttributes = new string[] { "class", "style", "data-" };

// -------------------------------
// Cleanup
// -------------------------------
Console.WriteLine($"Cleaning target folder {targetFolder}...");
if (Directory.Exists(targetFolder))
{
	Directory.Delete(targetFolder, recursive: true);
}

Directory.CreateDirectory(targetFolder);

// -------------------------------
// Global attributes
// -------------------------------
Console.WriteLine("Fetching global attributes");

var globalAttributes = HtmlAttributes.Fetch(
	"https://developer.mozilla.org/en-US/docs/Web/HTML/Reference/Global_attributes"
);

var globalAttributesBuilder = new StringBuilder();
globalAttributesBuilder.AppendLine("// <auto-generated/>");
globalAttributesBuilder.AppendLine("#nullable enable");
globalAttributesBuilder.AppendLine($"namespace {targetNamespace};");
globalAttributesBuilder.AppendLine();
globalAttributesBuilder.AppendLine("using RobinEpple.Common.Html;");
globalAttributesBuilder.AppendLine();
globalAttributesBuilder.AppendLine("public partial class HtmlTag");
globalAttributesBuilder.AppendLine("{");
foreach (var attribute in globalAttributes)
{
	if (excludeAttributes.Contains(attribute.Name))
	{
		continue;
	}
	globalAttributesBuilder.AppendLine(Helper.Indent(HtmlAttributes.Render(attribute, "HtmlTag")));
}
globalAttributesBuilder.AppendLine("}");

var globalAttributesSource = globalAttributesBuilder.ToString();
File.WriteAllText(Path.Combine(targetFolder, "HtmlTag.cs"), globalAttributesSource);

Console.WriteLine($"{globalAttributes.Count} global attributes found.");
